  function detect() {
    try {
      const saved = localStorage.getItem(STORAGE);
      if (saved === "en" || saved === "zh") return saved;
    } catch (_) {}
    const nav = (navigator.language || navigator.userLanguage || "en").toLowerCase();
    return nav.startsWith("zh") ? "zh" : "en";
  }

  function t(lang, key) {
    return (dict[lang] && dict[lang][key]) || (dict.en && dict.en[key]) || key;
  }

  function apply(lang) {
    document.documentElement.lang = lang === "zh" ? "zh-Hans" : "en";
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      if (el.tagName === "META") return;
      const key = el.getAttribute("data-i18n");
      const val = t(lang, key);
      if (el.hasAttribute("data-i18n-html") || /<[a-z][\s\S]*>/i.test(val)) el.innerHTML = val;
      else el.textContent = val;
    });
    document.querySelectorAll("[data-i18n-html]").forEach((el) => {
      if (el.hasAttribute("data-i18n")) return; // already handled
      const key = el.getAttribute("data-i18n-html");
      el.innerHTML = t(lang, key);
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      el.setAttribute("placeholder", t(lang, el.getAttribute("data-i18n-placeholder")));
    });
    document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
      el.setAttribute("aria-label", t(lang, el.getAttribute("data-i18n-aria")));
    });
    document.querySelectorAll("[data-i18n-alt]").forEach((el) => {
      el.setAttribute("alt", t(lang, el.getAttribute("data-i18n-alt")));
    });
    const titleKey = document.documentElement.getAttribute("data-i18n-title") || "meta.title";
    const title = t(lang, titleKey);
    if (title) document.title = title;
    const desc = document.querySelector('meta[name="description"]');
    if (desc) {
      const descKey = desc.getAttribute("data-i18n") || "meta.desc";
      desc.setAttribute("content", t(lang, descKey));
    }
    document.querySelectorAll(".lang-switch [data-lang]").forEach((btn) => {
      const on = btn.getAttribute("data-lang") === lang;
      btn.setAttribute("aria-pressed", on ? "true" : "false");
      btn.classList.toggle("is-active", on);
    });
    try { localStorage.setItem(STORAGE, lang); } catch (_) {}
    document.dispatchEvent(new CustomEvent("noy:lang", { detail: { lang } }));
  }

  function bindSwitcher() {
    document.querySelectorAll(".lang-switch [data-lang]").forEach((btn) => {
      btn.addEventListener("click", () => apply(btn.getAttribute("data-lang")));
    });
  }

  window.NoYI18n = { dict, pieces, detect, apply, t, bindSwitcher, STORAGE };
